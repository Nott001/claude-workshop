// Transpiles config/payments.yaml into a TypeScript module the bundlers can
// reach. Cloudflare Workers have no filesystem at runtime, so the config is
// compiled into the bundle instead of read from disk — this script is that
// compile step. It stays a dumb copy (no parsing): the schema and validation
// live in src/modules/commerce/lib/payment-config.ts, where tests can reach it.
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = dirname(dirname(fileURLToPath(import.meta.url)));
const source = join(root, "config", "payments.yaml");
const target = join(root, "src", "modules", "commerce", "lib", "payment-config.generated.ts");

const yaml = readFileSync(source, "utf8");
const escaped = yaml.replace(/\\/g, "\\\\").replace(/`/g, "\\`").replace(/\$\{/g, "\\${");

const output = [
  "// DO NOT EDIT - generated by scripts/sync-payment-config.mjs from config/payments.yaml.",
  "// Regenerate after editing the config with `pnpm sync:payment-config`.",
  `export const PAYMENT_CONFIG_YAML = \`${escaped}\`;`,
  "",
].join("\n");

writeFileSync(target, output);
console.log(`synced ${source} -> ${target}`);
